// a time into a long recording, as h:mm:ss or m:ss
const clock = (sec) => {
  const x = Math.round(sec);
  const hh = Math.floor(x / 3600), mm = Math.floor((x % 3600) / 60), ss = String(x % 60).padStart(2, "0");
  return hh ? `${hh}:${String(mm).padStart(2, "0")}:${ss}` : `${mm}:${ss}`;
};

